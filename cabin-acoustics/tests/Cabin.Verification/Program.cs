var evidence = new List<object>();
void Check(string name, bool condition)
{
    evidence.Add(new { name, passed = condition });
    if (!condition)
        throw new Exception("FAILED: " + name);
    Console.WriteLine("PASS " + name);
}
void Near(string name, double actual, double expected, double tolerance = 1e-8)
    => Check(name, Math.Abs(actual - expected) <= tolerance);
void Reject(string name, Action action)
{
    try { action(); }
    catch (ArgumentException) { Check(name, true); return; }
    Check(name, false);
}
