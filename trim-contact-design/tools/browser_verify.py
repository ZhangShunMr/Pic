    def nav(name):
        target=page.locator('nav').get_by_role('button',name=re.compile(re.escape(name)+'$'))
        target.click()
        expect(target).to_have_class(re.compile('nav-active'))
    def status(text): expect(page.locator('.status')).to_contain_text(text)
    def apply(): button('应用编辑').first.click()
