from pathlib import Path
from datetime import datetime,timezone
import json,urllib.request
from playwright.sync_api import sync_playwright,expect
ROOT=Path(__file__).resolve().parents[1]
checks=[]
def record(name,value=True):
 assert value,name
 checks.append({'name':name,'passed':True})
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
 page=b.new_page(viewport={'width':1440,'height':1000},accept_downloads=True)
 page.set_default_timeout(8000)
 page.on('dialog',lambda d:d.accept())
 page.goto('http://127.0.0.1:8774');page.wait_for_timeout(1000)
 def click(name):
  page.get_by_role('button',name=name,exact=True).first.click();page.wait_for_timeout(160)
 page.locator('.library-open').filter(has_text='附件电机频率闭环验证').first.click()
 page.wait_for_timeout(200)
 page.locator('#delivery .export-grid').evaluate('(e)=>e.scrollIntoView({block:"center",behavior:"instant"})')
 page.wait_for_timeout(200)
 page.screenshot(path=str(ROOT/'docs/screenshots/18-成果导出.png'))
 click('载入独立模拟示例')
 click('归档项目');click('确认继续')
 click('应用电机条件')
 expect(page.locator('#status-message')).to_contain_text('已归档')
 record('归档阻止内容编辑')
 click('取消归档');click('确认继续')
 click('应用电机条件')
 expect(page.locator('#status-message')).to_contain_text('完成')
 record('取消归档恢复编辑')
 page.get_by_role('button',name='删除频段',exact=True).first.click()
 click('确认继续')
 record('删除频段确认后引用更新',page.locator('.band-card').count()==1)
 page.locator('#orders summary').filter(has_text='添加或管理').click()
 click('删除候选');click('确认继续')
 record('删除自定义候选并更新图表','二倍转频待验证' not in page.locator('#orders table').inner_text())
 before=page.locator('.candidate-line').count()
 page.locator('#orders table input[type=checkbox]').first.uncheck();page.wait_for_timeout(200)
 record('隐藏候选后图线减少',page.locator('.candidate-line').count()==before-1)
 page.locator('.spectrum-chip').get_by_role('button',name='删除',exact=True).click();click('取消，保留当前工作')
 record('删除频谱可取消且原始数据保留',page.locator('.spectrum-chip').count()==1)
 page.locator('.snapshot').get_by_role('button',name='删除快照',exact=True).click();click('确认继续')
 record('删除快照后比较显示空状态',page.locator('.snapshot').count()==0)
 malformed=Path('/tmp/motor-invalid-version.motorproj')
 malformed.write_text('{"formatVersion":99}')
 page.locator('.project-rail input[type=file]').set_input_files(str(malformed))
 expect(page.locator('#status-message')).to_contain_text('不支持')
 record('真实UI拒绝未知格式且当前项目保留','60 Hz' in page.locator('.project-strip').inner_text())
 page.locator('.motor-callouts').get_by_role('button',name='项目档案',exact=False).click()
 page.get_by_label('项目名称',exact=True).fill('测'*100)
 click('应用项目档案')
 record('100字项目名称不造成整页横向溢出',page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
 page.locator('#delivery summary').filter(has_text='项目输入核对表').click()
 with page.expect_download() as d:click('导出输入核对 JSON')
 path=ROOT/'docs/sample-exports/输入核对-模拟.json';d.value.save_as(str(path))
 value=json.loads(path.read_text())
 record('输入核对JSON实际下载包含证据项',len(value['items'])>5 and value['source']=='模拟演示')
 page.get_by_role('button',name='读取上一版备份为副本',exact=True).first.click();click('确认继续')
 expect(page.locator('.project-strip')).to_contain_text('备份恢复')
 record('项目库备份实际恢复为新副本')
 page.close();b.close()
with urllib.request.urlopen('http://127.0.0.1:8774/_framework/blazor.web.js') as response:
 record('Production模式静态框架脚本可用',response.status==200 and len(response.read())>1000)
(ROOT/'docs/supplementary-evidence.json').write_text(json.dumps({'at':datetime.now(timezone.utc).isoformat(),'checks':checks},ensure_ascii=False,indent=2))
print('Supplementary passed:',len(checks))
