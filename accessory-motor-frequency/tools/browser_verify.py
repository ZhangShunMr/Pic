    evidence={'at':datetime.now(timezone.utc).isoformat(),'browser':browser.version,'viewport':'1440x1000 / 1024x900 / 390x844','checks':checks,'pageErrors':errors,'screenshots':[f.name for f in SHOTS.glob('*.png')],'downloads':[{'file':f.name,'bytes':f.stat().st_size,'sha256':hashlib.sha256(f.read_bytes()).hexdigest()} for f in DOWNLOADS.iterdir()]}
    (OUT/'browser-evidence.json').write_text(json.dumps(evidence,ensure_ascii=False,indent=2))
    print(json.dumps({'passed':len(checks),'pageErrors':errors,'screenshots':len(evidence['screenshots'])},ensure_ascii=False))
    browser.close()
