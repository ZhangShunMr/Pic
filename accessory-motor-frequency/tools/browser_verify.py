    def wait(): page.wait_for_timeout(160)
    def click(name,exact=True):
        page.get_by_role('button',name=name,exact=exact).first.click()
        wait()
    def fill(name,value):
        page.get_by_label(name,exact=True).fill(value)
        page.get_by_label(name,exact=True).blur()
        wait()
    def shot(name,selector=None):
        if selector:
            page.locator(selector).evaluate('(e)=>e.scrollIntoView({block:"start",behavior:"instant"})')
            wait()
        else: page.evaluate('scrollTo({top:0,behavior:"instant"})')
        page.screenshot(path=str(SHOTS/name))
    def download(name):
        with page.expect_download() as item:
            page.get_by_role('button',name=re.compile('^'+re.escape(name))).first.click()
        download=item.value
        target=DOWNLOADS/download.suggested_filename
        download.save_as(target)
        record('实际下载 '+name,target.stat().st_size>20,str(target.name))
        return target
